def main() -> int:
    print("\n" + "═" * 64)
    print("  Draw2Trade · 피드 게시글 시드 (Firestore)")
    print("═" * 64)

    created = 0
    skipped = 0
    failed  = 0
    for p in POSTS:
        slug = p["slug"]
        existing = feed_service.get_post_by_slug(slug)
        if existing:
            print(f"  ⏭  {slug:35} 이미 존재 (id={existing.get('id')[:8]}...) — skip")
            skipped += 1
            continue

        nid = feed_service.create_post(p)
        if nid:
            print(f"  ✅ {slug:35} 생성 (id={nid[:8]}...)")
            created += 1
        else:
            print(f"  ❌ {slug:35} 실패")
            failed += 1

    print("─" * 64)
    print(f"  결과: 생성 {created} · 스킵 {skipped} · 실패 {failed}")
    return 0 if failed == 0 else 1


